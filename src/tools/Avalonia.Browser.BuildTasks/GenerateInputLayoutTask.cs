using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

namespace Avalonia.Browser.BuildTasks;

/// <summary>
/// Generates inputLayout.g.ts from <see cref="BrowserInputLayout"/>: a const enum per struct with its field offsets
/// and $size, and a const enum per enum with its values.
/// </summary>
public class GenerateInputLayoutTask : Task
{
    [Required]
    public string OutputFile { get; set; } = null!;

    public override bool Execute()
    {
        try
        {
            var types = typeof(BrowserInputLayout).GetNestedTypes(BindingFlags.Public)
                .OrderBy(t => t.MetadataToken)
                .ToArray();

            var ts = new StringBuilder()
                .AppendLine("// <auto-generated>")
                .AppendLine("// Generated from BrowserInputLayout.cs by Avalonia.Browser.BuildTasks. Do not edit.")
                .AppendLine("// Struct members are byte offsets, $size is the struct size; field types are in comments.")
                .AppendLine("// </auto-generated>");

            foreach (var type in types.Where(t => t.IsEnum))
                AppendEnum(ts, type);
            foreach (var type in types.Where(t => t.IsValueType && !t.IsEnum))
                AppendStruct(ts, type);

            File.WriteAllText(OutputFile, ts.ToString().Replace("\r\n", "\n"));
            return true;
        }
        catch (InvalidOperationException e)
        {
            Log.LogError("BrowserInputLayout: " + e.Message);
            return false;
        }
    }

    private static void AppendEnum(StringBuilder ts, Type type)
    {
        ts.AppendLine().AppendLine($"export const enum {type.Name} {{");
        foreach (var field in type.GetFields(BindingFlags.Public | BindingFlags.Static))
            ts.AppendLine($"    {field.Name} = {Convert.ToInt32(field.GetValue(null))},");
        ts.AppendLine("}");
    }

    private static void AppendStruct(StringBuilder ts, Type type)
    {
        // Pack = 1 rules out padding, so offsets computed here hold on the WASM runtime too.
        if (type.StructLayoutAttribute is not { Value: LayoutKind.Sequential, Pack: 1 })
            throw new InvalidOperationException($"{type.Name} must be [StructLayout(LayoutKind.Sequential, Pack = 1)].");

        var size = Marshal.SizeOf(type);
        ts.AppendLine().AppendLine($"export const enum {type.Name} {{").AppendLine($"    $size = {size},");

        // JS typed array indexing and WASM atomics need naturally aligned fields.
        var end = 0;
        foreach (var field in type.GetFields(BindingFlags.Public | BindingFlags.Instance)
                     .OrderBy(f => (int)Marshal.OffsetOf(type, f.Name)))
        {
            var offset = (int)Marshal.OffsetOf(type, field.Name);
            if (offset != end)
                throw new InvalidOperationException($"{type.Name}.{field.Name} at offset {offset} follows padding.");
            if (offset % AlignmentOf(field.FieldType) != 0)
                throw new InvalidOperationException($"{type.Name}.{field.Name} at offset {offset} is misaligned.");

            ts.AppendLine($"    /** {TypeName(field.FieldType)} */").AppendLine($"    {field.Name} = {offset},");
            end = offset + SizeOf(field.FieldType);
        }

        if (end != size)
            throw new InvalidOperationException($"{type.Name} has trailing padding.");
        if (size % AlignmentOf(type) != 0)
            throw new InvalidOperationException($"{type.Name} size {size} is not a multiple of its alignment.");

        ts.AppendLine("}");
    }

    private static string TypeName(Type type)
    {
        if (type.IsEnum && Enum.GetUnderlyingType(type) == typeof(int))
            return $"i32 ({type.Name})";
        if (type == typeof(int))
            return "i32";
        if (type == typeof(float))
            return "f32";
        if (type == typeof(double))
            return "f64";
        if (type.IsValueType && type.DeclaringType == typeof(BrowserInputLayout))
            return type.Name;
        throw new InvalidOperationException($"{type} is not a supported field type.");
    }

    private static int SizeOf(Type type) => type.IsEnum ? sizeof(int) : Marshal.SizeOf(type);

    private static int AlignmentOf(Type type)
    {
        TypeName(type);
        if (type.IsEnum || type == typeof(int) || type == typeof(float))
            return 4;
        if (type == typeof(double))
            return 8;
        return type.GetFields(BindingFlags.Public | BindingFlags.Instance).Max(f => AlignmentOf(f.FieldType));
    }
}
