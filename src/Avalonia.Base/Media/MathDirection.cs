namespace Avalonia.Media
{
    /// <summary>
    /// The direction in which a math glyph grows through its size variants and glyph assembly.
    /// </summary>
    public enum MathDirection
    {
        /// <summary>
        /// Growing in width, as for horizontal braces, arrows and wide accents.
        /// </summary>
        Horizontal,

        /// <summary>
        /// Growing in height, as for delimiters, radicals and large operators.
        /// </summary>
        Vertical,
    }
}
